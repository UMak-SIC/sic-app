CREATE TYPE "ShortUrlStatus" AS ENUM ('active', 'disabled');

CREATE TABLE "short_urls" (
  "id" UUID NOT NULL,
  "code" TEXT COLLATE "C" NOT NULL,
  "name" TEXT NOT NULL DEFAULT 'Untitled link',
  "destination" TEXT NOT NULL,
  "view_count" BIGINT NOT NULL DEFAULT 0,
  "status" "ShortUrlStatus" NOT NULL DEFAULT 'active',
  "expires_at" TIMESTAMPTZ(6),
  "qr_logo_asset_id" UUID,
  "qr_foreground" TEXT NOT NULL DEFAULT '#176b4f',
  "qr_background" TEXT NOT NULL DEFAULT '#f9f9ee',
  "created_by_admin_id" TEXT NOT NULL,
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMPTZ(6) NOT NULL,

  CONSTRAINT "short_urls_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "short_urls_code_key" UNIQUE ("code"),
  CONSTRAINT "short_urls_code_format" CHECK ("code" ~ '^[A-Za-z]{7}$'),
  CONSTRAINT "short_urls_destination_https" CHECK (
    "destination" ~ '^https://[^/?#[:space:]]+([/?#].*)?$'
    AND "destination" !~ '[[:space:]]'
  ),
  CONSTRAINT "short_urls_view_count_nonnegative" CHECK ("view_count" >= 0)
);

CREATE TABLE "short_url_visits" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "short_url_id" UUID NOT NULL,
  "visited_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT "short_url_visits_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "short_urls_created_by_admin_id_created_at_idx"
  ON "short_urls"("created_by_admin_id", "created_at");
CREATE INDEX "short_urls_status_expires_at_idx"
  ON "short_urls"("status", "expires_at");
CREATE INDEX "short_url_visits_short_url_id_visited_at_idx"
  ON "short_url_visits"("short_url_id", "visited_at");

ALTER TABLE "short_urls"
  ADD CONSTRAINT "short_urls_created_by_admin_id_fkey"
  FOREIGN KEY ("created_by_admin_id") REFERENCES "admins"("neon_auth_user_id")
  ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "short_urls"
  ADD CONSTRAINT "short_urls_qr_logo_asset_id_fkey"
  FOREIGN KEY ("qr_logo_asset_id") REFERENCES "assets"("id")
  ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "short_url_visits"
  ADD CONSTRAINT "short_url_visits_short_url_id_fkey"
  FOREIGN KEY ("short_url_id") REFERENCES "short_urls"("id")
  ON DELETE CASCADE ON UPDATE CASCADE;
